import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { env } from '../config/env';

/** Maximum receipt size accepted by the API and mobile picker. */
export const MAX_RECEIPT_BYTES = 5 * 1024 * 1024;

export type ReceiptMimeType = 'image/jpeg' | 'image/png' | 'image/webp';

const RECEIPT_DIRECTORY = 'receipts';
const MIME_EXTENSIONS: Record<ReceiptMimeType, string> = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
};

/**
 * Receipts live outside the source tree and outside any public static route.
 * `UPLOAD_DIR` lets deployments point this at a mounted persistent volume.
 */
export const UPLOAD_ROOT = path.resolve(
  env.UPLOAD_DIR?.trim() || path.join(process.cwd(), 'uploads'),
);
export const RECEIPT_ROOT = path.join(UPLOAD_ROOT, RECEIPT_DIRECTORY);

export interface StoredReceipt {
  storageKey: string;
  mimeType: ReceiptMimeType;
  originalName: string | null;
  sizeBytes: number;
}

export function isAllowedReceiptMime(value: string): value is ReceiptMimeType {
  return Object.prototype.hasOwnProperty.call(MIME_EXTENSIONS, value);
}

/**
 * Reads the file signature rather than trusting the browser-supplied MIME
 * header. This prevents a text or executable payload from being stored just
 * because it was labelled as an image.
 */
export function detectImageMime(buffer: Buffer): ReceiptMimeType | null {
  if (buffer.length >= 3 && buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) {
    return 'image/jpeg';
  }

  const pngSignature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  if (buffer.length >= 8 && buffer.subarray(0, 8).equals(pngSignature)) {
    return 'image/png';
  }

  if (
    buffer.length >= 12 &&
    buffer.toString('ascii', 0, 4) === 'RIFF' &&
    buffer.toString('ascii', 8, 12) === 'WEBP'
  ) {
    return 'image/webp';
  }

  return null;
}

/** Stores only a display-safe basename; the generated storage key is used on disk. */
export function sanitizeOriginalName(originalName: string | null | undefined): string | null {
  if (!originalName) return null;

  const basename = path.basename(originalName.replace(/\\/g, '/'));
  const safe = basename
    .normalize('NFKC')
    .replace(/[^a-zA-Z0-9._ -]/g, '_')
    .trim()
    .slice(0, 180);

  return safe || null;
}

/**
 * Resolves a database storage key inside the upload root.
 *
 * The key is generated by this module, but this check also protects against a
 * corrupt or manually edited row containing `../` or an absolute path.
 */
export function resolveReceiptPath(storageKey: string): string | null {
  if (!storageKey.startsWith(`${RECEIPT_DIRECTORY}/`)) return null;

  const resolved = path.resolve(UPLOAD_ROOT, storageKey);
  const relative = path.relative(UPLOAD_ROOT, resolved);
  if (relative.startsWith('..') || path.isAbsolute(relative)) return null;

  return resolved;
}

export async function storeReceipt(
  buffer: Buffer,
  mimeType: ReceiptMimeType,
  originalName: string | null,
): Promise<StoredReceipt> {
  const extension = MIME_EXTENSIONS[mimeType];
  const filename = `${crypto.randomUUID()}${extension}`;
  const storageKey = `${RECEIPT_DIRECTORY}/${filename}`;
  const absolutePath = resolveReceiptPath(storageKey);

  if (!absolutePath) throw new Error('Unable to resolve receipt storage path');

  await fs.promises.mkdir(RECEIPT_ROOT, { recursive: true });
  // `wx` refuses to overwrite an existing file, even in the unlikely event of
  // a UUID collision.
  await fs.promises.writeFile(absolutePath, buffer, { flag: 'wx' });

  return {
    storageKey,
    mimeType,
    originalName: sanitizeOriginalName(originalName),
    sizeBytes: buffer.length,
  };
}

/** Best-effort cleanup. Missing files are already in the desired state. */
export async function deleteReceiptFile(storageKey: string): Promise<boolean> {
  const absolutePath = resolveReceiptPath(storageKey);
  if (!absolutePath) return false;

  try {
    await fs.promises.unlink(absolutePath);
    return true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false;
    throw error;
  }
}
